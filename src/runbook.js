// Script export
// ─────────────────────────────────────────────────────────────────

export function scriptFormatForPath(exportPath) {
  const ext = path.extname(String(exportPath || "")).toLowerCase();
  if (ext === ".ps1") return "powershell";
  if (ext === ".bat" || ext === ".cmd") return "batch";
  return "bash";
}

export function buildRunbookScript(commands, notes, options = {}) {
  const { format = "bash", title = "", blockedList = [] } = options;
  const comment = format === "batch" ? "REM" : "#";
  const lines = [];

  if (format === "bash") {
    lines.push("#!/usr/bin/env bash");
  } else if (format === "batch") {
    lines.push("@echo off");
  }
  if (title) lines.push(`${comment} Runbook: ${title}`);
  lines.push(`${comment} Generated by gac. Review every command before running.`);
  if (format === "bash") {
    lines.push("set -euo pipefail");
  } else if (format === "powershell") {
    lines.push('$ErrorActionPreference = "Stop"');
  }
  lines.push("");

  commands.forEach((entry, index) => {
    if (entry.description) {
      lines.push(`${comment} Step ${index + 1}: ${entry.description}`);
    } else {
      lines.push(`${comment} Step ${index + 1}`);
    }
    const blocked = findBlockedCommand(entry.command, blockedList);
    if (blocked) {
      const reason = blocked.reason || "matches a guarded destructive pattern";
      lines.push(`${comment} BLOCKED (${reason}) - left commented out on purpose:`);
      lines.push(`${comment} ${entry.command}`);
    } else {
      lines.push(entry.command);
    }
    lines.push("");
  });

  if (notes.length) {
    lines.push(`${comment} Notes:`);
    notes.forEach((note) => lines.push(`${comment} - ${note}`));
    lines.push("");
  }

  return lines.join("\n");
}

// ─────────────────────────────────────────────────────────────────
// Command runners (persistent POSIX shell / per-step Windows)
// ─────────────────────────────────────────────────────────────────

function createRunbookShell() {
  const shell = process.env.SHELL || "bash";
  const child = spawn(shell, ["-l"], { stdio: "pipe" });
  const session = {
    child,
    pending: null,
    closed: false,
  };

  const finalizePending = (result) => {
    if (!session.pending) return;
    const pending = session.pending;
    session.pending = null;
    pending.resolve(result);
  };

  const handleStdout = (data) => {
    const text = data.toString();
    const pending = session.pending;
    if (!pending) {
      term(text);
      return;
    }
    pending.buffer += text;
    let output = "";
    while (true) {
      const markerIndex = pending.buffer.indexOf(pending.marker);
      if (markerIndex === -1) {
        output += pending.buffer;
        pending.buffer = "";
        break;
      }
      output += pending.buffer.slice(0, markerIndex);
      const afterMarker = pending.buffer.slice(markerIndex + pending.marker.length);
      const endIndex = afterMarker.indexOf("__");
      if (endIndex === -1) {
        pending.buffer = pending.buffer.slice(markerIndex);
        break;
      }
      const exitCode = Number.parseInt(afterMarker.slice(0, endIndex), 10);
      pending.exitCode = Number.isNaN(exitCode) ? 1 : exitCode;
      pending.buffer = afterMarker.slice(endIndex + 2);
      pending.done = true;
    }
    if (output) {
      pending.stdout += output;
      term(output);
    }
    if (pending.done) {
      finalizePending({
        code: pending.exitCode ?? 0,
        stdout: pending.stdout,
        stderr: pending.stderr,
      });
    }
  };

  const handleStderr = (data) => {
    const text = data.toString();
    const pending = session.pending;
    if (pending) {
      pending.stderr += text;
    }
    term(text);
  };

  child.stdout.on("data", handleStdout);
  child.stderr.on("data", handleStderr);
  child.on("error", (err) => {
    const message = `Failed to start command: ${err.message}\n`;
    if (session.pending) {
      session.pending.stderr += message;
      finalizePending({ code: 1, stdout: session.pending.stdout, stderr: session.pending.stderr });
    }
    term(message);
    session.closed = true;
  });
  child.on("close", (code) => {
    session.closed = true;
    if (session.pending) {
      const message = `Shell session ended unexpectedly (exit code ${code ?? "unknown"}).\n`;
      session.pending.stderr += message;
      finalizePending({ code: code ?? 1, stdout: session.pending.stdout, stderr: session.pending.stderr });
      term(message);
    }
  });

  child.stdin.write("set -o pipefail\n");
  return session;
}

function closeRunbookShell(session) {
  if (!session || session.closed) return;
  session.child.stdin.end("exit\n");
}

function runShellCommand(session, command) {
  if (!session || session.closed) {
    return Promise.resolve({
      code: 1,
      stdout: "",
      stderr: "Shell session is not available.\n",
    });
  }
  return new Promise((resolve) => {
    const token = `gac_${Date.now()}_${Math.random().toString(16).slice(2)}`;
    const marker = `__GAC_EXIT__${token}__:`;
    session.pending = {
      resolve,
      stdout: "",
      stderr: "",
      buffer: "",
      marker,
      done: false,
      exitCode: null,
    };
    session.child.stdin.write(`${command}\n`);
    session.child.stdin.write(`__gac_status=$?\n`);
    session.child.stdin.write(
      `printf "__GAC_EXIT__${token}__:%s__\\n" "$__gac_status"\n`
    );
  });
}

// `cd` needs special handling on Windows because each step runs in its own
// cmd.exe process, so directory changes would not stick otherwise.
export function parseWindowsCdTarget(command) {
  const trimmed = String(command || "").trim();
  // Compound or redirected commands (cd x && ..., cd x > out) must run in the
  // real shell; only a bare cd is simulated in-process for cwd persistence.
  if (/[&|<>]/.test(trimmed)) return null;
  const match = trimmed.match(/^cd(?:\s+\/d)?(?:\s+(.+))?$/i);
  if (!match) return null;
  let target = (match[1] || "").trim();
  if (
    target.length >= 2 &&
    ((target.startsWith('"') && target.endsWith('"')) ||
      (target.startsWith("'") && target.endsWith("'")))
  ) {
    target = target.slice(1, -1);
  }
  return { target: target || null };
}

function createWindowsRunner() {
  let cwd = process.cwd();

  const run = (command) => {
    const cd = parseWindowsCdTarget(command);
    if (cd) {
      if (!cd.target) {
        term(`${cwd}\n`);
        return Promise.resolve({ code: 0, stdout: `${cwd}\n`, stderr: "" });
      }
      const next = path.resolve(cwd, cd.target);
      try {
        if (fs.statSync(next).isDirectory()) {
          cwd = next;
          return Promise.resolve({ code: 0, stdout: "", stderr: "" });
        }
      } catch (err) {
        // Fall through to the not-found error below.
      }
      const message = `The system cannot find the path specified: ${next}\n`;
      term(message);
      return Promise.resolve({ code: 1, stdout: "", stderr: message });
    }

    return new Promise((resolve) => {
      let settled = false;
      const finish = (result) => {
        if (settled) return;
        settled = true;
        resolve(result);
      };
      let stdout = "";
      let stderr = "";
      const child = spawn(command, { shell: true, cwd, stdio: "pipe" });
      child.stdout.on("data", (data) => {
        const text = data.toString();
        stdout += text;
        term(text);
      });
      child.stderr.on("data", (data) => {
        const text = data.toString();
        stderr += text;
        term(text);
      });
      child.on("error", (err) => {
        const message = `Failed to start command: ${err.message}\n`;
        stderr += message;
        term(message);
        finish({ code: 1, stdout, stderr });
      });
      child.on("close", (code) => {
        finish({ code: code ?? 1, stdout, stderr });
      });
    });
  };

  return { run, close: () => {} };
}

// Unified runner: a persistent login shell on POSIX (so cd/env persist across
// steps), a per-step cmd.exe with tracked cwd on Windows. Windows limitation:
// environment variables set in one step do not carry into the next.
export function createCommandRunner() {
  if (os.platform() === "win32") {
    return createWindowsRunner();
  }
  const session = createRunbookShell();
  return {
    run: (command) => runShellCommand(session, command),
    close: () => closeRunbookShell(session),
  };
}

