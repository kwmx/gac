// Interactive flow
// ─────────────────────────────────────────────────────────────────

function printRunbookCommands(commands) {
  commands.forEach((entry, index) => {
    term(`${index + 1}. `);
    if (entry.description) {
      term(`${entry.description}\n   `);
    }
    term(`${entry.command}\n`);
  });
}

function printRemainingCommands(commands, startIndex) {
  if (startIndex >= commands.length) return;
  term("\nPlanned next commands:\n");
  commands.slice(startIndex).forEach((entry, offset) => {
    term(`${startIndex + offset + 1}. `);
    if (entry.description) {
      term(`${entry.description}\n   `);
    }
    term(`${entry.command}\n`);
  });
}

async function confirmRunbookStart(label) {
  term(label);
  return new Promise((resolve) => {
    term.grabInput({ mouse: "button" });
    const onKey = (name) => {
      term.grabInput(false);
      term.removeListener("key", onKey);
      term("\n");
      resolve(name === "ENTER");
    };
    term.on("key", onKey);
  });
}

// Per-step action prompt. Enter is disabled while the command matches a
// blocked pattern: it must be edited or skipped first.
async function promptRunbookAction(isBlocked) {
  if (isBlocked) {
    term.dim("[e] edit  [s] skip  [q] quit: ");
  } else {
    term.dim("[Enter] run  [e] edit  [s] skip  [q] quit: ");
  }
  return new Promise((resolve) => {
    term.grabInput({ mouse: "button" });
    const finish = (action) => {
      term.grabInput(false);
      term.removeListener("key", onKey);
      term("\n");
      resolve(action);
    };
    const onKey = (name) => {
      if (name === "ENTER" && !isBlocked) return finish("run");
      if (name === "e" || name === "E") return finish("edit");
      if (name === "s" || name === "S") return finish("skip");
      if (name === "q" || name === "Q" || name === "ESCAPE" || name === "CTRL_C") {
        return finish("quit");
      }
      // Ignore any other key so a stray keystroke can't run or abort a step.
    };
    term.on("key", onKey);
  });
}

async function editCommand(current) {
  term("Edit command:\n> ");
  return new Promise((resolve) => {
    term.inputField({ cancelable: true, default: String(current) }, (error, input) => {
      term("\n");
      if (error || input === undefined || input === null || !input.trim()) {
        resolve(current);
        return;
      }
      resolve(input.trim());
    });
  });
}

async function requestRunbookPlan(prompt, config, opts) {
  const system = buildSystemPrompt("runbook", config);
  const contextWindow = await resolveContextWindow(config);
  const budgetChars = Math.max(
    4000,
    (contextBudget(contextWindow, config.maxTokens) - estimateTokens(system) - 500) * 4
  );

  const contextParts = [buildRunbookContext()];
  if (opts.files && opts.files.length) {
    contextParts.push(formatFileContexts(opts.files, Math.floor(budgetChars / (2 * opts.files.length))));
  }

  let userPrompt = prompt;
  if (opts.piped) {
    // Head+tail truncation, same as ask/explain — the end of a log is
    // usually where the error is.
    const { text: piped } = truncateForContext(opts.piped, Math.floor(budgetChars / 2));
    userPrompt = attachInputToPrompt(prompt, piped);
  }

  const messages = [
    { role: "system", content: system },
    { role: "system", content: `Relevant context:\n${contextParts.join("\n\n")}` },
    { role: "user", content: userPrompt },
  ];
  const runbookConfig = {
    ...config,
    stream: false,
    renderMarkdown: false,
    debugRender: false,
  };

  const reply = await chatCompletion(runbookConfig, messages, { contextWindow });
  const payload = extractJsonPayload(reply);
  return normalizeRunbookCommands(payload);
}

export async function runRunbook(prompt, config, opts = {}) {
  const { commands, notes } = await requestRunbookPlan(prompt, config, opts);
  if (!commands.length) {
    term("No runnable commands were returned. Try rephrasing your request.\n");
    return;
  }

  const blockedList = loadBlockedCommands();

  term("Planned commands:\n");
  printRunbookCommands(commands);
  if (notes.length) {
    term("\nNotes:\n");
    notes.forEach((note) => term(`- ${note}\n`));
  }
  term("\n");

  if (opts.exportPath) {
    const format = scriptFormatForPath(opts.exportPath);
    const script = buildRunbookScript(commands, notes, {
      format,
      title: prompt,
      blockedList,
    });
    const resolved = path.resolve(process.cwd(), opts.exportPath);
    fs.writeFileSync(resolved, script, format === "bash" ? { mode: 0o755 } : undefined);
    term(`Runbook written to ${resolved}. Nothing was executed.\n`);
    return;
  }

  if (opts.dryRun) {
    term("Dry run: no commands were executed.\n");
    return;
  }

  if (!opts.interactive) {
    term(
      "Not an interactive terminal: showing the plan only. Use --export <path> to save it as a script.\n"
    );
    return;
  }

  const ready = await confirmRunbookStart(
    "Press Enter to start running the runbook (any other key to cancel): "
  );
  if (!ready) {
    term("Runbook execution canceled.\n");
    return;
  }

  const runner = createCommandRunner();
  for (let i = 0; i < commands.length; i += 1) {
    const entry = commands[i];

    term(`\nStep ${i + 1} of ${commands.length}:\n`);
    if (entry.description) {
      term(`${entry.description}\n`);
    }

    let action;
    while (true) {
      term(`Command: ${entry.command}\n`);
      const blocked = findBlockedCommand(entry.command, blockedList);
      if (blocked) {
        term.red(
          `Blocked: ${blocked.reason || "matches a guarded destructive pattern"}\n`
        );
      }
      action = await promptRunbookAction(Boolean(blocked));
      if (action === "edit") {
        entry.command = await editCommand(entry.command);
        continue;
      }
      break;
    }

    if (action === "skip") {
      term.dim(`Skipped step ${i + 1}.\n`);
      continue;
    }
    if (action === "quit") {
      term(`Stopped at step ${i + 1}.\n`);
      printRemainingCommands(commands, i);
      runner.close();
      return;
    }

    term(`\n$ ${entry.command}\n`);
    const result = await runner.run(entry.command);
    if (result.code !== 0) {
      term(
        `\nCommand failed (step ${i + 1}) with exit code ${result.code}. Stopping.\n`
      );
      if (result.stderr.trim()) {
        term(`Issue:\n${result.stderr}\n`);
      }
      printRemainingCommands(commands, i + 1);
      runner.close();
      return;
    }
    term("\n");
  }

  runner.close();
  term("All commands completed successfully.\n");
}
